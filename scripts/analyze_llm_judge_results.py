from __future__ import annotations

import argparse
import csv
import json
import math
from collections import defaultdict
from itertools import combinations
from pathlib import Path
from typing import Any


RUBRIC_CATEGORIES = {
    "supported_by_data": [
        "unsupported",
        "partially_supported",
        "mostly_supported",
        "fully_supported",
    ],
    "sensor_phq9_integration": ["absent", "partial", "adequate", "strong"],
    "evidence_quality": ["poor", "limited", "sufficient", "strong"],
    "explanatory_power": ["low", "moderate", "high"],
    "clinical_plausibility": ["low", "moderate", "high"],
    "extrapolation": ["severe", "moderate", "minor", "none"],
    "uncertainty_missing_data": ["ignored", "limited", "adequate", "clear"],
    "clarity": ["poor", "fair", "good", "excellent"],
    "clinical_usefulness": ["not_useful", "limited", "useful", "very_useful"],
    "missing_relevant_information": ["many", "some", "few", "none"],
}
RUBRIC_CRITERIA = list(RUBRIC_CATEGORIES)
OVERALL_ASSESSMENTS = ["very_weak", "weak", "moderate", "strong", "very_strong"]

CATEGORY_SCORES = {
    criterion: {value: index for index, value in enumerate(values)}
    for criterion, values in RUBRIC_CATEGORIES.items()
}
OVERALL_SCORES = {value: index for index, value in enumerate(OVERALL_ASSESSMENTS)}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Analyze rubric-based LLM-as-a-Judge results for qualitative PHQ-9 "
            "and passive-sensing explanations."
        )
    )
    parser.add_argument(
        "--evaluations",
        default=Path("outputs/llm_judge_evaluations_raw.jsonl"),
        type=Path,
        help="JSONL generated by scripts/run_llm_judge_evaluation.py.",
    )
    parser.add_argument(
        "--case-output",
        default=Path("outputs/llm_judge_evaluation_cases.csv"),
        type=Path,
        help="Output CSV with one row per successful judge evaluation.",
    )
    parser.add_argument(
        "--summary-output",
        default=Path("outputs/llm_judge_evaluation_summary.csv"),
        type=Path,
        help="Output CSV summarizing scores by generator model.",
    )
    parser.add_argument(
        "--agreement-output",
        default=Path("outputs/llm_judge_agreement.csv"),
        type=Path,
        help="Output CSV with inter-judge agreement by criterion.",
    )
    parser.add_argument(
        "--report-output",
        default=Path("outputs/llm_judge_evaluation_report.md"),
        type=Path,
        help="Output Markdown report summarizing qualitative judge results.",
    )
    return parser.parse_args()


def get_parsed_response(row: dict[str, Any]) -> dict[str, Any] | None:
    parsed_response = row.get("parsed_response")
    if isinstance(parsed_response, dict):
        return parsed_response
    if isinstance(parsed_response, str) and parsed_response.strip():
        try:
            parsed = json.loads(parsed_response)
        except json.JSONDecodeError:
            return None
        if isinstance(parsed, dict):
            return parsed
    return None


def prediction_sort_key(row: dict[str, Any]) -> tuple[str, str]:
    return (str(row.get("timestamp", "")), str(row.get("run_id", "")))


def read_latest_evaluations(path: Path) -> dict[tuple[str, str, str, str, str], dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"Missing evaluations file: {path}")

    latest: dict[tuple[str, str, str, str, str], dict[str, Any]] = {}
    with path.open("r", encoding="utf-8") as handle:
        for line_number, raw_line in enumerate(handle, start=1):
            line = raw_line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: invalid JSONL: {exc}") from exc

            values = [
                row.get("judge_provider"),
                row.get("judge_model"),
                row.get("generator_provider"),
                row.get("generator_model"),
                row.get("case_id"),
            ]
            if not all(isinstance(value, str) and value.strip() for value in values):
                continue
            key = tuple(str(value) for value in values)
            if key not in latest or prediction_sort_key(row) >= prediction_sort_key(latest[key]):
                latest[key] = row

    if not latest:
        raise ValueError(f"No judge evaluations found in {path}")
    return latest


def validate_judge_response(parsed_response: dict[str, Any], expected_case_id: str) -> list[str]:
    errors: list[str] = []

    criteria = parsed_response.get("criteria")
    if not isinstance(criteria, dict):
        errors.append("criteria must be an object")
    else:
        actual_criteria = set(criteria.keys())
        expected_criteria = set(RUBRIC_CRITERIA)
        if actual_criteria != expected_criteria:
            errors.append(
                "unexpected criteria keys: "
                f"missing={sorted(expected_criteria - actual_criteria)}, "
                f"extra={sorted(actual_criteria - expected_criteria)}"
            )
        for criterion, allowed_values in RUBRIC_CATEGORIES.items():
            value = criteria.get(criterion)
            if value not in allowed_values:
                errors.append(f"criteria.{criterion} has invalid value: {value!r}")

    if parsed_response.get("case_id") != expected_case_id:
        errors.append(
            f"case_id mismatch: expected {expected_case_id}, "
            f"found {parsed_response.get('case_id')!r}"
        )

    overall_assessment = parsed_response.get("overall_assessment")
    if overall_assessment not in OVERALL_ASSESSMENTS:
        errors.append(f"overall_assessment has invalid value: {overall_assessment!r}")

    return errors


def round_or_blank(value: float | None) -> str:
    if value is None or math.isnan(value):
        return ""
    return f"{value:.4f}"


def mean(values: list[float]) -> float | None:
    if not values:
        return None
    return sum(values) / len(values)


def stdev(values: list[float]) -> float | None:
    if len(values) < 2:
        return None
    value_mean = sum(values) / len(values)
    variance = sum((value - value_mean) ** 2 for value in values) / (len(values) - 1)
    return math.sqrt(variance)


def flatten_successful_rows(rows: list[dict[str, Any]]) -> tuple[list[dict[str, str]], dict[str, int]]:
    flattened: list[dict[str, str]] = []
    status_counts: dict[str, int] = defaultdict(int)

    for row in rows:
        status = str(row.get("status", ""))
        status_counts[status] += 1
        if status != "success":
            continue

        case_id = str(row["case_id"])
        parsed_response = get_parsed_response(row)
        if parsed_response is None:
            status_counts["invalid_parsed_response"] += 1
            continue

        validation_errors = validate_judge_response(parsed_response, case_id)
        if validation_errors:
            status_counts["invalid_success_response"] += 1
            continue

        criteria = parsed_response["criteria"]
        flat_row = {
            "judge_provider": str(row["judge_provider"]),
            "judge_model": str(row["judge_model"]),
            "generator_provider": str(row["generator_provider"]),
            "generator_model": str(row["generator_model"]),
            "case_id": case_id,
            "same_provider_family": str(row["judge_provider"] == row["generator_provider"]),
            "run_id": str(row.get("run_id", "")),
            "generator_run_id": str(row.get("generator_run_id", "")),
            "timestamp": str(row.get("timestamp", "")),
            "overall_assessment": str(parsed_response["overall_assessment"]),
            "overall_score": str(OVERALL_SCORES[str(parsed_response["overall_assessment"])]),
        }
        for criterion in RUBRIC_CRITERIA:
            value = str(criteria[criterion])
            flat_row[criterion] = value
            flat_row[f"{criterion}_score"] = str(CATEGORY_SCORES[criterion][value])
        flattened.append(flat_row)

    status_counts["successful_valid_rows"] = len(flattened)
    return flattened, dict(status_counts)


def build_summary_rows(case_rows: list[dict[str, str]]) -> list[dict[str, str]]:
    grouped: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in case_rows:
        key = (row["generator_provider"], row["generator_model"])
        grouped[key].append(row)

    summary_rows: list[dict[str, str]] = []
    for (generator_provider, generator_model), rows in sorted(grouped.items()):
        unique_cases = {row["case_id"] for row in rows}
        unique_judges = {f"{row['judge_provider']}|{row['judge_model']}" for row in rows}
        cross_family_rows = [
            row for row in rows if row["same_provider_family"].lower() != "true"
        ]
        output_row = {
            "generator_provider": generator_provider,
            "generator_model": generator_model,
            "successful_judgments": str(len(rows)),
            "cross_family_judgments": str(len(cross_family_rows)),
            "unique_cases": str(len(unique_cases)),
            "unique_judges": str(len(unique_judges)),
            "avg_overall_score": round_or_blank(
                mean([float(row["overall_score"]) for row in rows])
            ),
            "std_overall_score": round_or_blank(
                stdev([float(row["overall_score"]) for row in rows])
            ),
            "avg_overall_score_cross_family": round_or_blank(
                mean([float(row["overall_score"]) for row in cross_family_rows])
            ),
            "std_overall_score_cross_family": round_or_blank(
                stdev([float(row["overall_score"]) for row in cross_family_rows])
            ),
        }
        for criterion in RUBRIC_CRITERIA:
            scores = [float(row[f"{criterion}_score"]) for row in rows]
            cross_family_scores = [
                float(row[f"{criterion}_score"]) for row in cross_family_rows
            ]
            output_row[f"avg_{criterion}_score"] = round_or_blank(mean(scores))
            output_row[f"std_{criterion}_score"] = round_or_blank(stdev(scores))
            output_row[f"avg_{criterion}_score_cross_family"] = round_or_blank(
                mean(cross_family_scores)
            )
            output_row[f"std_{criterion}_score_cross_family"] = round_or_blank(
                stdev(cross_family_scores)
            )
        summary_rows.append(output_row)

    return summary_rows


def average_pairwise_agreement(items: dict[str, list[str]]) -> float | None:
    item_scores: list[float] = []
    for values in items.values():
        if len(values) < 2:
            continue
        pairs = list(combinations(values, 2))
        if not pairs:
            continue
        agreements = sum(1 for left, right in pairs if left == right)
        item_scores.append(agreements / len(pairs))

    return mean(item_scores)


def all_judges_exact_agreement(items: dict[str, list[str]], judge_count: int) -> float | None:
    complete_items = [
        values for values in items.values() if len(values) == judge_count and judge_count >= 2
    ]
    if not complete_items:
        return None
    agreed = sum(1 for values in complete_items if len(set(values)) == 1)
    return agreed / len(complete_items)


def fleiss_kappa(
    items: dict[str, list[str]],
    categories: list[str],
    judge_count: int,
) -> float | None:
    if judge_count < 2:
        return None

    complete_items = [
        values for values in items.values() if len(values) == judge_count
    ]
    if not complete_items:
        return None

    category_index = {category: index for index, category in enumerate(categories)}
    n_items = len(complete_items)
    n_categories = len(categories)
    category_totals = [0] * n_categories
    item_agreements: list[float] = []

    for values in complete_items:
        counts = [0] * n_categories
        for value in values:
            counts[category_index[value]] += 1
        for index, count in enumerate(counts):
            category_totals[index] += count
        agreement = (sum(count * count for count in counts) - judge_count) / (
            judge_count * (judge_count - 1)
        )
        item_agreements.append(agreement)

    mean_observed = sum(item_agreements) / n_items
    category_proportions = [
        category_total / (n_items * judge_count) for category_total in category_totals
    ]
    expected = sum(proportion * proportion for proportion in category_proportions)
    denominator = 1 - expected
    if abs(denominator) < 1e-12:
        return None
    return (mean_observed - expected) / denominator


def build_agreement_rows(case_rows: list[dict[str, str]]) -> list[dict[str, str]]:
    judge_ids = sorted({f"{row['judge_provider']}|{row['judge_model']}" for row in case_rows})
    judge_count = len(judge_ids)
    rows: list[dict[str, str]] = []

    agreement_targets = {
        **RUBRIC_CATEGORIES,
        "overall_assessment": OVERALL_ASSESSMENTS,
    }

    for criterion, categories in agreement_targets.items():
        items: dict[str, list[str]] = defaultdict(list)
        for row in case_rows:
            item_id = f"{row['generator_provider']}|{row['generator_model']}|{row['case_id']}"
            items[item_id].append(row[criterion])

        items_with_ratings = len(items)
        items_with_at_least_2 = sum(1 for values in items.values() if len(values) >= 2)
        items_with_all_judges = sum(1 for values in items.values() if len(values) == judge_count)

        rows.append(
            {
                "criterion": criterion,
                "judges": str(judge_count),
                "items_with_ratings": str(items_with_ratings),
                "items_with_at_least_2_judges": str(items_with_at_least_2),
                "items_with_all_judges": str(items_with_all_judges),
                "average_pairwise_agreement": round_or_blank(
                    average_pairwise_agreement(items)
                ),
                "all_judges_exact_agreement": round_or_blank(
                    all_judges_exact_agreement(items, judge_count)
                ),
                "fleiss_kappa_complete_items": round_or_blank(
                    fleiss_kappa(items, categories, judge_count)
                ),
            }
        )

    return rows


def write_csv(path: Path, rows: list[dict[str, str]], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def build_report(
    summary_rows: list[dict[str, str]],
    agreement_rows: list[dict[str, str]],
    status_counts: dict[str, int],
) -> str:
    lines = [
        "# Qualitative LLM-as-a-Judge Evaluation",
        "",
        "This report summarizes rubric-based, referenceless evaluations of qualitative explanations.",
        "",
        "Higher ordinal scores indicate more desirable outcomes for every criterion. "
        "For `extrapolation`, `none` is better than `severe`; for "
        "`missing_relevant_information`, `none` is better than `many`.",
        "",
        "Agreement among LLM judges improves confidence in consistency, but it is not external clinical validation.",
        "",
        "## Status Counts",
        "",
        "| status | count |",
        "| --- | ---: |",
    ]

    for status, count in sorted(status_counts.items()):
        lines.append(f"| {status} | {count} |")

    lines.extend(["", "## Generator Summary", ""])
    if not summary_rows:
        lines.append("No successful valid judge evaluations found.")
    else:
        summary_columns = [
            "generator_provider",
            "generator_model",
            "successful_judgments",
            "cross_family_judgments",
            "unique_cases",
            "unique_judges",
            "avg_overall_score",
            "avg_overall_score_cross_family",
            "avg_supported_by_data_score",
            "avg_supported_by_data_score_cross_family",
            "avg_sensor_phq9_integration_score",
            "avg_sensor_phq9_integration_score_cross_family",
            "avg_evidence_quality_score",
            "avg_evidence_quality_score_cross_family",
            "avg_extrapolation_score",
            "avg_extrapolation_score_cross_family",
            "avg_uncertainty_missing_data_score",
            "avg_uncertainty_missing_data_score_cross_family",
            "avg_clinical_usefulness_score",
            "avg_clinical_usefulness_score_cross_family",
        ]
        lines.append("| " + " | ".join(summary_columns) + " |")
        lines.append("| " + " | ".join(["---"] * len(summary_columns)) + " |")
        for row in summary_rows:
            lines.append("| " + " | ".join(row[column] for column in summary_columns) + " |")

    lines.extend(["", "## Inter-Judge Agreement", ""])
    if not agreement_rows:
        lines.append("No agreement rows found.")
    else:
        agreement_columns = [
            "criterion",
            "judges",
            "items_with_at_least_2_judges",
            "items_with_all_judges",
            "average_pairwise_agreement",
            "all_judges_exact_agreement",
            "fleiss_kappa_complete_items",
        ]
        lines.append("| " + " | ".join(agreement_columns) + " |")
        lines.append("| " + " | ".join(["---"] * len(agreement_columns)) + " |")
        for row in agreement_rows:
            lines.append("| " + " | ".join(row[column] for column in agreement_columns) + " |")

    lines.extend(
        [
            "",
            "## Interpretation Notes",
            "",
            "- `average_pairwise_agreement` averages exact-match agreement across all available judge pairs for each evaluated explanation.",
            "- `all_judges_exact_agreement` uses only items evaluated by every judge and requires all judges to choose the same category.",
            "- `fleiss_kappa_complete_items` uses only items evaluated by every judge, because Fleiss' kappa assumes a fixed number of raters per item.",
            "- Columns ending in `_cross_family` exclude judgments where the judge provider and generator provider are the same.",
            "- These metrics measure consistency among judges, not correctness against a ground truth.",
        ]
    )

    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()
    latest_rows = read_latest_evaluations(args.evaluations)
    case_rows, status_counts = flatten_successful_rows(
        [
            row
            for _, row in sorted(
                latest_rows.items(),
                key=lambda item: (item[0][2], item[0][3], item[0][4], item[0][0], item[0][1]),
            )
        ]
    )

    summary_rows = build_summary_rows(case_rows)
    agreement_rows = build_agreement_rows(case_rows)

    case_fieldnames = [
        "judge_provider",
        "judge_model",
        "generator_provider",
        "generator_model",
        "case_id",
        "same_provider_family",
        "run_id",
        "generator_run_id",
        "timestamp",
        "overall_assessment",
        "overall_score",
    ]
    for criterion in RUBRIC_CRITERIA:
        case_fieldnames.extend([criterion, f"{criterion}_score"])

    summary_fieldnames = [
        "generator_provider",
        "generator_model",
        "successful_judgments",
        "cross_family_judgments",
        "unique_cases",
        "unique_judges",
        "avg_overall_score",
        "std_overall_score",
        "avg_overall_score_cross_family",
        "std_overall_score_cross_family",
    ]
    for criterion in RUBRIC_CRITERIA:
        summary_fieldnames.extend(
            [
                f"avg_{criterion}_score",
                f"std_{criterion}_score",
                f"avg_{criterion}_score_cross_family",
                f"std_{criterion}_score_cross_family",
            ]
        )

    agreement_fieldnames = [
        "criterion",
        "judges",
        "items_with_ratings",
        "items_with_at_least_2_judges",
        "items_with_all_judges",
        "average_pairwise_agreement",
        "all_judges_exact_agreement",
        "fleiss_kappa_complete_items",
    ]

    write_csv(args.case_output, case_rows, case_fieldnames)
    write_csv(args.summary_output, summary_rows, summary_fieldnames)
    write_csv(args.agreement_output, agreement_rows, agreement_fieldnames)

    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.write_text(
        build_report(summary_rows, agreement_rows, status_counts),
        encoding="utf-8",
    )

    print(f"Saved case-level judge evaluations: {args.case_output}")
    print(f"Saved generator summary: {args.summary_output}")
    print(f"Saved inter-judge agreement: {args.agreement_output}")
    print(f"Saved report: {args.report_output}")
    print(f"Successful valid judge rows: {len(case_rows)}")
    print("Validation: PASS")


if __name__ == "__main__":
    main()
