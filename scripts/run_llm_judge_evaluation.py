def read_text(path: Path) -> str:
    if not path.exists():
        raise FileNotFoundError(f"Missing file: {path}")
    return path.read_text(encoding="utf-8")


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(read_text(path))


def read_cases(path: Path) -> dict[str, dict[str, Any]]:
    if not path.exists():
        raise FileNotFoundError(f"Missing file: {path}")

    cases: dict[str, dict[str, Any]] = {}
    with path.open("r", encoding="utf-8") as handle:
        for line_number, raw_line in enumerate(handle, start=1):
            line = raw_line.strip()
            if not line:
                continue
            try:
                case = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: invalid JSONL: {exc}") from exc

            case_id = case.get("case_id")
            if not isinstance(case_id, str) or not case_id.strip():
                raise ValueError(f"{path}:{line_number}: missing case_id")
            if case_id in cases:
                raise ValueError(f"Duplicated case_id in {path}: {case_id}")
            cases[case_id] = case

    if not cases:
        raise ValueError(f"No cases found in {path}")
    return cases


def parse_model_json(response_text: str) -> tuple[dict[str, Any] | None, str | None]:
    stripped = response_text.strip()
    candidates = [stripped]

    fenced_match = re.search(r"```(?:json)?\s*(.*?)\s*```", stripped, flags=re.DOTALL)
    if fenced_match:
        candidates.append(fenced_match.group(1).strip())

    for candidate in candidates:
        try:
            parsed = json.loads(candidate)
        except json.JSONDecodeError:
            continue

        if isinstance(parsed, dict):
            return parsed, None
        return None, "Parsed JSON is not an object."

    return None, "Response is not valid JSON."


def count_sentences(text: str) -> int:
    stripped = text.strip()
    if not stripped:
        return 0

    sentence_like_chunks = [
        chunk.strip()
        for chunk in re.split(r"(?<=[.!?])\s+", stripped)
        if chunk.strip()
    ]
    if sentence_like_chunks:
        return len(sentence_like_chunks)

    return 1


def validate_generated_explanation(
    parsed_response: dict[str, Any],
    expected_case_id: str,
) -> list[str]:
    errors: list[str] = []

    expected_keys = {
        "case_id",
        "behavioral_summary",
        "phq9_summary",
        "cross_analysis",
        "unsupported_or_weak_links",
        "uncertainties",
        "overall_assessment",
    }
    actual_keys = set(parsed_response.keys())
    if actual_keys != expected_keys:
        missing_keys = sorted(expected_keys - actual_keys)
        extra_keys = sorted(actual_keys - expected_keys)
        errors.append(
            "unexpected generated explanation keys: "
            f"missing={missing_keys}, extra={extra_keys}"
        )

    if parsed_response.get("case_id") != expected_case_id:
        errors.append(
            f"case_id mismatch: expected {expected_case_id}, "
            f"found {parsed_response.get('case_id')!r}"
        )

    for field_name in ["behavioral_summary", "phq9_summary"]:
        value = parsed_response.get(field_name)
        if not isinstance(value, str) or not value.strip():
            errors.append(f"{field_name} is missing or empty")
        elif not (1 <= count_sentences(value) <= 3):
            errors.append(f"{field_name} must contain 1 to 3 sentences")

    cross_analysis = parsed_response.get("cross_analysis")
    if not isinstance(cross_analysis, list):
        errors.append("cross_analysis must be a list")
    else:
        expected_cross_keys = {
            "phq9_item",
            "symptom_label",
            "support_level",
            "behavioral_evidence",
            "caution",
        }
        for index, entry in enumerate(cross_analysis):
            if not isinstance(entry, dict):
                errors.append(f"cross_analysis[{index}] must be an object")
                continue
            actual_cross_keys = set(entry.keys())
            if actual_cross_keys != expected_cross_keys:
                missing_cross_keys = sorted(expected_cross_keys - actual_cross_keys)
                extra_cross_keys = sorted(actual_cross_keys - expected_cross_keys)
                errors.append(
                    "cross_analysis"
                    f"[{index}] unexpected keys: missing={missing_cross_keys}, "
                    f"extra={extra_cross_keys}"
                )
                continue

            phq9_item = entry.get("phq9_item")
            if phq9_item not in {f"item_{item_index}" for item_index in range(1, 10)}:
                errors.append(f"cross_analysis[{index}].phq9_item is invalid")

            support_level = entry.get("support_level")
            if support_level not in ALLOWED_SUPPORT_LEVELS:
                errors.append(
                    f"cross_analysis[{index}].support_level is invalid: "
                    f"{support_level!r}"
                )

            for field_name in ["symptom_label", "behavioral_evidence", "caution"]:
                value = entry.get(field_name)
                if not isinstance(value, str) or not value.strip():
                    errors.append(f"cross_analysis[{index}].{field_name} is empty")

            behavioral_evidence = entry.get("behavioral_evidence")
            if isinstance(behavioral_evidence, str) and not (
                1 <= count_sentences(behavioral_evidence) <= 2
            ):
                errors.append(
                    "cross_analysis"
                    f"[{index}].behavioral_evidence must contain 1 or 2 sentences"
                )

            caution = entry.get("caution")
            if isinstance(caution, str) and not (1 <= count_sentences(caution) <= 2):
                errors.append(f"cross_analysis[{index}].caution must contain 1 or 2 sentences")

    for field_name in ["unsupported_or_weak_links", "uncertainties"]:
        value = parsed_response.get(field_name)
        if not isinstance(value, list):
            errors.append(f"{field_name} must be a list")
        elif not all(isinstance(item, str) and item.strip() for item in value):
            errors.append(f"{field_name} must contain only non-empty strings")

    overall_assessment = parsed_response.get("overall_assessment")
    if not isinstance(overall_assessment, str) or not overall_assessment.strip():
        errors.append("overall_assessment is missing or empty")

    return errors


def get_parsed_response(row: dict[str, Any]) -> dict[str, Any] | None:
    parsed_response = row.get("parsed_response")
    if isinstance(parsed_response, dict):
        return parsed_response
    if isinstance(parsed_response, str) and parsed_response.strip():
        try:
            parsed = json.loads(parsed_response)
        except json.JSONDecodeError:
            return None
        if isinstance(parsed, dict):
            return parsed
    return None


def prediction_sort_key(row: dict[str, Any]) -> tuple[str, str]:
    return (str(row.get("timestamp", "")), str(row.get("run_id", "")))


def read_latest_valid_predictions(
    path: Path,
    cases: dict[str, dict[str, Any]],
    limit: int | None,
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    if not path.exists():
        raise FileNotFoundError(f"Missing predictions file: {path}")

    latest: dict[tuple[str, str, str], dict[str, Any]] = {}
    status_counts: dict[str, int] = {}

    with path.open("r", encoding="utf-8") as handle:
        for line_number, raw_line in enumerate(handle, start=1):
            line = raw_line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: invalid JSONL: {exc}") from exc

            status = str(row.get("status", ""))
            status_counts[status] = status_counts.get(status, 0) + 1
            if status != "success":
                continue

            provider = row.get("provider")
            model = row.get("model")
            case_id = row.get("case_id")
            if not all(isinstance(value, str) and value.strip() for value in [provider, model, case_id]):
                continue

            key = (str(provider), str(model), str(case_id))
            if key not in latest or prediction_sort_key(row) >= prediction_sort_key(latest[key]):
                latest[key] = row

    valid_rows: list[dict[str, Any]] = []
    excluded_missing_case = 0
    excluded_invalid_generation = 0
    for row in sorted(latest.values(), key=lambda item: (item["provider"], item["model"], item["case_id"])):
        case_id = str(row["case_id"])
        if case_id not in cases:
            excluded_missing_case += 1
            continue

        parsed_response = get_parsed_response(row)
        if parsed_response is None:
            excluded_invalid_generation += 1
            continue

        validation_errors = validate_generated_explanation(parsed_response, case_id)
        if validation_errors:
            excluded_invalid_generation += 1
            continue

        valid_rows.append(row)
        if limit is not None and len(valid_rows) >= limit:
            break

    status_counts["valid_latest_explanations"] = len(valid_rows)
    status_counts["excluded_missing_case"] = excluded_missing_case
    status_counts["excluded_invalid_generation"] = excluded_invalid_generation
    return valid_rows, status_counts


